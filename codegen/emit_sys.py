"""The guest side in Rust: sys/src/bindings.gen.rs, the declarations of <wasmer/gui.h>.

Names are the header's, so that what is written about the C API reads the same
here. Layout is the header's too (`#[repr(C)]`), and the file asserts every
size and offset the generator computed when it is compiled for wasm32.
"""

import textwrap

from emit_c import flag_literal, member_decl
from spec import FN_PREFIX, HEADER_SIZE, PREFIX, RUST_KEYWORDS, pascal

BANNER = "// Generated by codegen/gen.py from spec/gui.json and spec/keys.json. Do not edit.\n"
WIDTH = 96

C_TO_RUST = {
    "uint32_t": "u32",
    "int32_t": "i32",
    "uint64_t": "u64",
    "size_t": "usize",
    "float": "f32",
    "double": "f64",
    "char": "u8",
    "void": "core::ffi::c_void",
}


def comment(text, indent=""):
    if not text.strip():
        return []
    lines = []
    for paragraph in text.strip("\n").split("\n\n"):
        if lines:
            lines.append("")
        rows = paragraph.split("\n")
        if all(row.startswith("    ") for row in rows):
            # Code in the header's language: shown as it is, and not compiled as Rust.
            lines += ["```c"] + [row[4:].rstrip() for row in rows] + ["```"]
        else:
            lines += textwrap.wrap(" ".join(paragraph.split()), WIDTH - len(indent) - 4)
    return [(indent + "/// " + line).rstrip() for line in lines]


def ident(name):
    """A C name as a Rust identifier: the header has a field called `type`."""
    return "r#" + name if name in RUST_KEYWORDS else name


def rust_type(ctype):
    """The Rust spelling of a C type of the header."""
    const = ctype.startswith("const ")
    t = ctype[6:] if const else ctype
    if t.endswith("*"):
        inner = t[:-1]
        return ("*const " if const else "*mut ") + C_TO_RUST.get(inner, inner)
    return C_TO_RUST.get(t, t)


def literal(spec, ctype, value):
    """(Rust type, expression) of a constant of the spec."""
    named = {
        "version": ("u32", "0x%08X" % spec.version),
        "usize_max": ("usize", "usize::MAX"),
        "uint32_max": ("u32", "u32::MAX"),
        "uint64_max": ("u64", "u64::MAX"),
        "int32_min": ("i32", "i32::MIN"),
    }
    if value in named:
        return named[value]
    return {"uint32": "u32", "int32": "i32", "uint64": "u64", "usize": "usize"}[ctype], str(value)


def member_default(spec, m):
    """The Rust initializers of a struct member, as in the header's INIT macro."""
    t = m.ty
    if t.array:
        return ["0", "core::ptr::null()"]
    if t.pointer:
        return ["core::ptr::null()" if t.pointer == "immutable" else "core::ptr::null_mut()"]
    if t.kind == "string":
        return [PREFIX + "StringView::INIT"]
    if t.kind == "struct":
        return [spec.struct_by_name[t.base].c_name + "::INIT"]
    if t.kind == "bitflag":
        flag = spec.bitflag_by_name[t.base]
        names = t.default or []
        if not isinstance(names, list):
            names = [names]
        value = 0
        for n in names:
            value |= flag.value(n)
        return [flag_literal(flag, value)]
    if t.kind == "enum":
        enum = spec.enum_by_name[t.base]
        if t.default:
            return [spec.enum_entry_c(t.base, t.default)]
        zero = [n for n, v, _ in enum.entries if v == 0]
        return [spec.enum_entry_c(t.base, zero[0])] if zero else ["0"]
    if t.default and str(t.default).startswith("constant."):
        return ["%s_%s" % (PREFIX, t.default.split(".", 1)[1].upper())]
    if t.kind == "prim" and t.base in ("float32", "float64"):
        text = str(t.default) if t.default else "0.0"
        return [text if "." in text else text + ".0"]
    if t.default:
        return [str(t.default)]
    return ["0"]


def struct_fields(spec, s):
    """[(rust type, name, default or None, doc)] of a struct, the fields every kind starts with included."""
    fields = []
    if s.kind == "extensible":
        fields.append(("*mut %sChainedStruct" % PREFIX, "nextInChain", "core::ptr::null_mut()", ""))
    elif s.kind == "extension":
        fields.append(("%sChainedStruct" % PREFIX, "chain", None, ""))
    elif s.kind == "record":
        fields.append(("%sEventHeader" % PREFIX, "header", None, ""))
    for m in s.members:
        decls = member_decl(spec, m)
        defaults = member_default(spec, m)
        for i, ((ctype, cname), default) in enumerate(zip(decls, defaults)):
            doc = m.doc if i == len(decls) - 1 or len(decls) == 1 else ""
            fields.append((rust_type(ctype), cname, default, doc))
    return fields


def emit_struct(spec, s, out):
    fields = struct_fields(spec, s)
    out += comment(s.doc)
    out.append("#[repr(C)]")
    out.append("#[derive(Clone, Copy, Debug)]")
    out.append("pub struct %s {" % s.c_name)
    for rtype, name, _, doc in fields:
        out += comment(doc, "    ")
        out.append("    pub %s: %s," % (ident(name), rtype))
    out.append("}")
    if s.kind in ("extensible", "standalone"):
        out.append("")
        out.append("impl %s {" % s.c_name)
        out.append("    /// What the header's `%s` is." % s.init_name)
        out.append("    pub const INIT: Self = Self {")
        for _, name, default, _ in fields:
            out.append("        %s: %s," % (ident(name), default))
        out.append("    };")
        out.append("}")
        out.append("")
        out.append("impl Default for %s {" % s.c_name)
        out.append("    fn default() -> Self {")
        out.append("        Self::INIT")
        out.append("    }")
        out.append("}")
    out.append("")


def emit_layout(spec, s, out):
    """Assertions that the Rust compiler lays `s` out as the generator computed."""
    if s.size is None:
        return
    out.append("    assert!(size_of::<%s>() == %d);" % (s.c_name, s.size))
    for m in s.members:
        if m.offset is None:
            continue
        name = m.c_count_name if m.ty.array else m.c_name
        out.append("    assert!(offset_of!(%s, %s) == %d);" % (s.c_name, ident(name), m.offset))


def emit_bindings(spec):
    P = PREFIX
    out = [BANNER.rstrip()]
    out.append("")
    out.append("// -- Constants " + "-" * 60)
    out.append("")
    out += comment("The WebAssembly module every function below is an import of.")
    out.append("pub const %s_IMPORT_MODULE: &str = \"%s\";" % (P, spec.import_module))
    out.append("")
    for name, ctype, value, doc in spec.constants:
        rtype, expression = literal(spec, ctype, value)
        out += comment(doc)
        out.append("pub const %s_%s: %s = %s;" % (P, name.upper(), rtype, expression))
        out.append("")

    out.append("// -- Basic types " + "-" * 58)
    out.append("")
    out.append("pub type %sBool = u32;" % P)
    out += comment("Sets of flags that have room for 64.")
    out.append("pub type %sFlags = u64;" % P)
    out.append("")
    out.append("// Handles are numbers the host gives out. 0 is never a handle. A handle works on")
    out.append("// every thread of the program, and using one after it was destroyed is an error")
    out.append("// the host reports, not a crash.")
    out.append("")
    for name, doc in spec.objects:
        out += comment(doc)
        out.append("pub type %s%s = u32;" % (P, pascal(name)))
        out.append("")
    out += comment("A string that need not end in NUL: `length` bytes at `data`, or up to the first NUL when `length` "
                   "is WGUI_STRLEN. UTF-8.")
    out.append("#[repr(C)]")
    out.append("#[derive(Clone, Copy, Debug)]")
    out.append("pub struct %sStringView {" % P)
    out.append("    pub data: *const u8,")
    out.append("    pub length: usize,")
    out.append("}")
    out.append("")
    out.append("impl %sStringView {" % P)
    out.append("    /// What the header's `%s_STRING_VIEW_INIT` is: no string." % P)
    out.append("    pub const INIT: Self = Self { data: core::ptr::null(), length: %s_STRLEN };" % P)
    out.append("")
    out.append("    /// The view of a string slice, which has to outlive every use of the view.")
    out.append("    pub const fn new(text: &str) -> Self {")
    out.append("        Self { data: text.as_ptr(), length: text.len() }")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("impl Default for %sStringView {" % P)
    out.append("    fn default() -> Self {")
    out.append("        Self::INIT")
    out.append("    }")
    out.append("}")
    out.append("")

    out.append("// -- Enumerations " + "-" * 57)
    out.append("")
    out.append("// A number and constants for it, not a Rust enum: a host may answer with a value")
    out.append("// this file does not name yet, which a Rust enum may not hold.")
    out.append("")
    for e in spec.enums:
        out += comment(e.doc)
        out.append("pub type %s = u32;" % e.c_name)
        for name, value, doc in e.entries:
            if e.name == "event_type":
                event = [ev for ev in spec.events if ev.name == name][0]
                record = "Record: %s." % spec.struct_by_name[event.record].c_name if event.record else "Header only."
                doc = (doc + " " if doc else "") + record
            out += comment(doc)
            out.append("pub const %s: %s = 0x%08X;" % (spec.enum_entry_c(e.name, name), e.c_name, value))
        out.append("")

    out.append("// -- Flags " + "-" * 64)
    out.append("")
    for b in spec.bitflags:
        out += comment(b.doc)
        out.append("pub type %s = %s;" % (b.c_name, "%sFlags" % P if b.width == 64 else "u32"))
        for name, value, doc in b.entries:
            out += comment(doc)
            out.append("pub const %s: %s = %s;" % (b.c_entry(name), b.c_name, flag_literal(b, value)))
        out.append("")

    out.append("// -- Keys " + "-" * 65)
    out.append("")
    out += comment(
        "What a key means on the user's layout: the KeyboardEvent `key` of the W3C UI Events specification, as a "
        "number. The top byte is a tag (WGUI_KEY_TAG) and the rest its value (WGUI_KEY_VALUE):\n\n"
        "WGUI_KEY_CHARACTER: the Unicode scalar value the key produces, so 'a' is 0x61. 0 is WGUIKey_Unidentified.\n\n"
        "WGUI_KEY_NAMED: one of the WGUIKey_* constants below.\n\n"
        "WGUI_KEY_DEAD: a dead key; the value is the combining character it adds, or 0.\n\n"
        "WGUI_KEY_SEQUENCE: more than one scalar value; the value is the first and the event's keyString has all.")
    out.append("pub type %sKey = u32;" % P)
    out.append("")
    out.append("pub const fn %s_KEY_TAG(key: %sKey) -> u32 {" % (P, P))
    out.append("    key & %s_KEY_TAG_MASK" % P)
    out.append("}")
    out.append("")
    out.append("pub const fn %s_KEY_VALUE(key: %sKey) -> u32 {" % (P, P))
    out.append("    key & %s_KEY_VALUE_MASK" % P)
    out.append("}")
    out.append("")
    out += comment("The named keys.")
    out.append("pub const %sKey_Unidentified: %sKey = 0x00000000;" % (P, P))
    for name, value in spec.named_keys:
        out.append("pub const %sKey_%s: %sKey = 0x%08X;" % (P, name, P, 0x01000000 | value))
    out.append("")

    out.append("// -- Structures " + "-" * 59)
    out.append("")
    out += comment("The start of a struct that extends another through its nextInChain list. Hosts skip structs they "
                   "do not know, unless the sType has WGUI_STYPE_MUST_UNDERSTAND set.")
    out.append("#[repr(C)]")
    out.append("#[derive(Clone, Copy, Debug)]")
    out.append("pub struct %sChainedStruct {" % P)
    out.append("    pub next: *mut %sChainedStruct," % P)
    out.append("    pub sType: %sSType," % P)
    out.append("}")
    out.append("")
    for s in spec.structs:
        emit_struct(spec, s, out)

    out.append("// -- Event records " + "-" * 56)
    out.append("")
    out += comment(spec.header.doc)
    out.append("#[repr(C)]")
    out.append("#[derive(Clone, Copy, Debug)]")
    out.append("pub struct %s {" % spec.header.c_name)
    for m in spec.header.members:
        out += comment(m.doc, "    ")
        out.append("    pub %s: %s," % (ident(m.c_name), rust_type(spec.c_type(m.ty))))
    out.append("}")
    out.append("")
    out += comment("A string inside an event record: `length` bytes of UTF-8 starting `offset` bytes from the start "
                   "of the record. An offset of 0 means there is no string. See wguiEventGetString.")
    out.append("#[repr(C)]")
    out.append("#[derive(Clone, Copy, Debug)]")
    out.append("pub struct %sEventString {" % P)
    out.append("    pub offset: u32,")
    out.append("    pub length: u32,")
    out.append("}")
    out.append("")
    for r in spec.records:
        emit_struct(spec, r, out)

    out.append("// -- Functions " + "-" * 60)
    out.append("")
    out.append("#[cfg_attr(target_family = \"wasm\", link(wasm_import_module = \"%s\"))]" % spec.import_module)
    out.append("extern \"C\" {")
    owner = object()
    for fn in spec.functions:
        if fn.owner != owner:
            owner = fn.owner
            out.append("    // %s" % (P + pascal(owner) if owner else "Global"))
            out.append("")
        doc = fn.doc
        if fn.blocking:
            doc += "\n\nMay block."
        out += comment(doc, "    ")
        params = ", ".join("%s: %s" % (ident(name), rust_type(ctype)) for ctype, name in spec.c_params(fn))
        result = {None: "", "status": " -> %sStatus" % P, "uint32": " -> u32", "bool": " -> %sBool" % P}[fn.returns]
        out.append("    pub fn %s(%s)%s;" % (fn.c_name, params, result))
        out.append("")
    if out[-1] == "":
        out.pop()
    out.append("}")
    out.append("")

    out.append("// -- Reading events " + "-" * 55)
    out.append("")
    H = spec.header.c_name
    out += comment("The first record in a buffer that wguiInstancePollEvents filled with `written` bytes, or null "
                   "when there is none.")
    out.append("///")
    out.append("/// # Safety")
    out.append("///")
    out.append("/// `buffer` has to be valid for reads of `written` bytes and aligned for a record.")
    out.append("pub unsafe fn %sEventFirst(buffer: *const u8, written: usize) -> *const %s {" % (FN_PREFIX, H))
    out.append("    let event = buffer.cast::<%s>();" % H)
    out.append("    if written < size_of::<%s>() {" % H)
    out.append("        return core::ptr::null();")
    out.append("    }")
    out.append("    let size = (*event).size as usize;")
    out.append("    if size < size_of::<%s>() || size > written {" % H)
    out.append("        return core::ptr::null();")
    out.append("    }")
    out.append("    event")
    out.append("}")
    out.append("")
    out += comment("The record after `event` in the same buffer, or null at the end.")
    out.append("///")
    out.append("/// # Safety")
    out.append("///")
    out.append("/// As for wguiEventFirst, and `event` has to be a record of that buffer.")
    out.append("pub unsafe fn %sEventNext(buffer: *const u8, written: usize, event: *const %s) -> *const %s {" % (
        FN_PREFIX, H, H))
    out.append("    let next = (event as usize - buffer as usize) + (*event).size as usize;")
    out.append("    if next >= written {")
    out.append("        return core::ptr::null();")
    out.append("    }")
    out.append("    %sEventFirst(buffer.add(next), written - next)" % FN_PREFIX)
    out.append("}")
    out.append("")
    out += comment("A string of a record. It points into the record: copy it to keep it. An absent string has null "
                   "data and length 0.")
    out.append("///")
    out.append("/// # Safety")
    out.append("///")
    out.append("/// `event` has to point to a whole record.")
    out.append("pub unsafe fn %sEventGetString(event: *const %s, string: %sEventString) -> %sStringView {" % (
        FN_PREFIX, H, P, P))
    out.append("    let size = (*event).size;")
    out.append("    if string.offset as usize >= size_of::<%s>()" % H)
    out.append("        && string.offset <= size")
    out.append("        && string.length <= size - string.offset")
    out.append("    {")
    out.append("        %sStringView {" % P)
    out.append("            data: event.cast::<u8>().add(string.offset as usize),")
    out.append("            length: string.length as usize,")
    out.append("        }")
    out.append("    } else {")
    out.append("        %sStringView { data: core::ptr::null(), length: 0 }" % P)
    out.append("    }")
    out.append("}")
    out.append("")

    out.append("// -- Layout " + "-" * 63)
    out.append("")
    out.append("// The header's layout is the one of the wasm32 C ABI, which is what the host decodes.")
    out.append("// Compiled for wasm32, the Rust compiler confirms every size and offset of it here.")
    out.append("#[cfg(target_pointer_width = \"32\")]")
    out.append("const _: () = {")
    out.append("    use core::mem::offset_of;")
    out.append("")
    out.append("    assert!(size_of::<%sStringView>() == 8);" % P)
    out.append("    assert!(size_of::<%sChainedStruct>() == 8);" % P)
    out.append("    assert!(size_of::<%s>() == %d);" % (H, HEADER_SIZE))
    out.append("    assert!(size_of::<%sEventString>() == 8);" % P)
    for s in spec.structs + spec.records:
        emit_layout(spec, s, out)
    out.append("};")
    return "\n".join(out) + "\n"
