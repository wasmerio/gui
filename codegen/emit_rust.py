"""Host-side Rust outputs: enums, struct readers and writers, event records,
the `*Api` traits with their import glue, and the import signature table."""

from spec import HEADER_SIZE, PREFIX, PRIMS, pascal, screaming, singular, snake

BANNER = "// Generated by codegen/gen.py from spec/gui.json and spec/keys.json. Do not edit.\n"

RUST_PRIM = {
    "bool": "bool", "uint32": "u32", "int32": "i32", "uint64": "u64", "usize": "u32",
    "float32": "f32", "float64": "f64", "key": "u32",
}
# How a scalar is stored in guest memory: (bytes, read expression, write statement).
STORE = {
    "u32": (4, "rd_u32(&b, %d)", "wr_u32(&mut b, %d, %s);"),
    "i32": (4, "rd_u32(&b, %d) as i32", "wr_u32(&mut b, %d, %s as u32);"),
    "u64": (8, "rd_u64(&b, %d)", "wr_u64(&mut b, %d, %s);"),
    "f32": (4, "f32::from_bits(rd_u32(&b, %d))", "wr_u32(&mut b, %d, %s.to_bits());"),
    "f64": (8, "f64::from_bits(rd_u64(&b, %d))", "wr_u64(&mut b, %d, %s.to_bits());"),
    "bool": (4, "rd_u32(&b, %d) != 0", "wr_u32(&mut b, %d, u32::from(%s));"),
}


def flag_type(spec, name):
    return "u64" if spec.bitflag_by_name[name].width == 64 else "u32"


def unique(names, what):
    seen = {}
    for original, made in names:
        if made in seen:
            raise SystemExit("%s: %s and %s both become %s" % (what, seen[made], original, made))
        seen[made] = original


# -- enums ---------------------------------------------------------------------

def emit_enums(spec):
    out = [BANNER]
    out.append("use super::{AbiEnum, AbiError, AbiResult};\n")
    for e in spec.enums:
        name = e.rust_name
        variants = [(spec.enum_entry_rust(e.name, n), v) for n, v, _ in e.entries]
        unique([(n, r) for (n, _, _), (r, _) in zip(e.entries, variants)], e.name)
        zero = [r for r, v in variants if v == 0]
        default = zero[0] if zero else variants[0][0]
        out.append("/// `%s`" % e.c_name)
        out.append("#[repr(u32)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
        out.append("pub enum %s {" % name)
        for variant, value in variants:
            out.append("    %s = 0x%X," % (variant, value))
        out.append("}")
        out.append("impl Default for %s {\n    fn default() -> Self {\n        Self::%s\n    }\n}" % (name, default))
        out.append("impl AbiEnum for %s {" % name)
        out.append("    const NAME: &'static str = \"%s\";" % e.c_name)
        out.append("    fn from_u32(value: u32) -> Option<Self> {")
        out.append("        Some(match value {")
        for variant, value in variants:
            out.append("            0x%X => Self::%s," % (value, variant))
        out.append("            _ => return None,")
        out.append("        })\n    }")
        out.append("    fn as_u32(self) -> u32 {\n        self as u32\n    }")
        out.append("    fn name(self) -> &'static str {")
        out.append("        match self {")
        for variant, _ in variants:
            out.append("            Self::%s => \"%s\"," % (variant, variant))
        out.append("        }\n    }\n}")
        out.append("impl %s {" % name)
        out.append("    /// Every value, in the order of the header.")
        out.append("    pub const ALL: &'static [Self] = &[")
        for variant, _ in variants:
            out.append("        Self::%s," % variant)
        out.append("    ];")
        out.append("    pub fn from_abi(value: u32) -> AbiResult<Self> {")
        out.append("        Self::from_u32(value).ok_or(AbiError::InvalidEnum { ty: Self::NAME, value })")
        out.append("    }\n}\n")
    for b in spec.bitflags:
        ty = flag_type(spec, b.name)
        out.append("/// `%s` (a `%s` in the C API)" % (b.c_name, "uint64_t" if ty == "u64" else "uint32_t"))
        out.append("pub mod %s {" % snake(b.name))
        for entry, value, _ in b.entries:
            out.append("    pub const %s: %s = 0x%X;" % (entry.upper(), ty, value))
        known = 0
        for _, value, _ in b.entries:
            known |= value
        out.append("    /// Every bit this version defines.")
        out.append("    pub const KNOWN: %s = 0x%X;" % (ty, known))
        out.append("    /// (name, bits) of the single-purpose entries, for printing.")
        out.append("    pub const NAMES: &[(&str, %s)] = &[" % ty)
        for entry, value, _ in b.entries:
            if value and value & (value - 1) == 0:
                out.append("        (\"%s\", 0x%X)," % (pascal(entry), value))
        out.append("    ];")
        out.append("}\n")

    out.append("/// Constants of the header.")
    for name, ctype, value, _ in spec.constants:
        rust = {"uint32": "u32", "usize": "u32", "uint64": "u64", "int32": "i32"}[ctype]
        text = {
            "version": "0x%08X" % spec.version, "usize_max": "u32::MAX", "uint32_max": "u32::MAX",
            "uint64_max": "u64::MAX", "int32_min": "i32::MIN",
        }.get(value, value)
        out.append("pub const %s: %s = %s;" % (name.upper(), rust, text))
    out.append("")
    out.append("/// Class numbers of event types: `type >> 8`.")
    out.append("pub mod event_class_number {")
    for name, value in sorted(spec.event_classes.items(), key=lambda kv: kv[1]):
        out.append("    pub const %s: u32 = %d;" % (name.upper(), value))
    out.append("}\n")

    consts = [(name, screaming(name)) for name, _ in spec.named_keys]
    unique(consts, "named keys")
    out.append("/// Named `WGUIKey` values: `WGUI_KEY_NAMED | number`.")
    out.append("pub mod key {")
    out.append("    pub const UNIDENTIFIED: u32 = 0;")
    for (name, value), (_, const) in zip(spec.named_keys, consts):
        out.append("    pub const %s: u32 = 0x%08X;" % (const, 0x01000000 | value))
    out.append("}\n")
    out.append("/// (W3C `key` value, `WGUIKey`) of every named key.")
    out.append("pub static NAMED_KEYS: &[(&str, u32)] = &[")
    for name, value in spec.named_keys:
        out.append("    (\"%s\", 0x%08X)," % (name, 0x01000000 | value))
    out.append("];")
    return "\n".join(out) + "\n"


# -- structs -------------------------------------------------------------------

def scalar(spec, ty):
    """The Rust storage type of a scalar member, or None."""
    if ty.array or ty.pointer:
        return None
    if ty.kind == "prim" and ty.base in RUST_PRIM:
        return RUST_PRIM[ty.base]
    if ty.kind == "bitflag":
        return flag_type(spec, ty.base)
    if ty.kind == "object":
        return "u32"
    return None


def field_type(spec, ty):
    """Rust type of a struct member in its decoded form."""
    if ty.kind == "string":
        return "String"
    if ty.array:
        if ty.kind in ("struct", "enum"):
            return "Vec<%s>" % pascal(ty.base)
        raise SystemExit("no array field type for " + ty.raw)
    if ty.pointer:
        return "u32"  # a guest address the implementation reads through
    if ty.kind == "enum":
        return pascal(ty.base)
    if ty.kind == "struct":
        return pascal(ty.base)
    t = scalar(spec, ty)
    if t is None:
        raise SystemExit("no field type for " + ty.raw)
    return t


def read_expr(spec, ty, o):
    if ty.kind == "string":
        return "mem.read_string(rd_u32(&b, %d), rd_u32(&b, %d))?" % (o, o + 4)
    if ty.array:
        count, ptr = "rd_u32(&b, %d)" % o, "rd_u32(&b, %d)" % (o + 4)
        if ty.kind == "struct":
            return "mem.read_array(%s, %s)?" % (ptr, count)
        return "mem.read_enum_array(%s, %s)?" % (ptr, count)
    if ty.pointer:
        return "rd_u32(&b, %d)" % o
    if ty.kind == "enum":
        return "%s::from_abi(rd_u32(&b, %d))?" % (pascal(ty.base), o)
    if ty.kind == "struct":
        return "%s::read(mem, ptr.wrapping_add(%d))?" % (pascal(ty.base), o)
    return STORE[scalar(spec, ty)][1] % o


def write_stmt(spec, ty, o, value):
    """Statement storing a member into the byte buffer `b`, or None when it is not a scalar."""
    if ty.array or ty.pointer or ty.kind == "string":
        return None
    if ty.kind == "enum":
        return "wr_u32(&mut b, %d, %s.as_u32());" % (o, value)
    if ty.kind == "struct":
        return None
    return STORE[scalar(spec, ty)][2] % (o, value)


def emit_structs(spec):
    out = [BANNER]
    out.append("use super::enums::*;")
    out.append("#[allow(unused_imports)]")
    out.append("use super::{rd_u32, rd_u64, wr_u32, wr_u64, AbiEnum, AbiResult, GuestMemory, GuestRead, GuestWrite};\n")
    for s in spec.structs:
        fields = [(snake(m.name), field_type(spec, m.ty), m) for m in s.members]
        out.append("/// `%s`: %d bytes, align %d on wasm32." % (s.c_name, s.size, s.align))
        out.append("#[derive(Clone, Debug, Default, PartialEq)]")
        out.append("pub struct %s {" % s.rust_name)
        for name, t, _ in fields:
            out.append("    pub %s: %s," % (name, t))
        out.append("}")
        if not s.written:
            out.append("impl GuestRead for %s {" % s.rust_name)
            out.append("    const SIZE: u32 = %d;" % s.size)
            out.append("    fn read(mem: &GuestMemory<'_>, ptr: u32) -> AbiResult<Self> {")
            out.append("        let b = mem.read_bytes::<%d>(ptr)?;" % s.size)
            if s.kind == "extensible":
                out.append("        mem.check_chain(rd_u32(&b, 0))?;")
            out.append("        Ok(Self {")
            for name, _, m in fields:
                out.append("            %s: %s," % (name, read_expr(spec, m.ty, m.offset)))
            out.append("        })\n    }\n}")
        if s.written or (s.kind == "standalone" and all(scalar(spec, m.ty) for m in s.members)):
            out.append("impl GuestWrite for %s {" % s.rust_name)
            out.append("    const SIZE: u32 = %d;" % s.size)
            out.append("    /// Stores the members, leaving `nextInChain` and padding as the guest set them.")
            out.append("    fn write(&self, mem: &GuestMemory<'_>, ptr: u32) -> AbiResult<()> {")
            out.append("        let mut b = mem.read_bytes::<%d>(ptr)?;" % s.size)
            nested = []
            for name, _, m in fields:
                stmt = write_stmt(spec, m.ty, m.offset, "self." + name)
                if stmt:
                    out.append("        " + stmt)
                elif m.ty.kind == "struct" and not m.ty.array and not m.ty.pointer:
                    nested.append((name, m))
                else:
                    raise SystemExit("%s.%s: the host cannot write a %s" % (s.name, m.name, m.ty.raw))
            out.append("        mem.write_bytes(ptr, &b)?;")
            for name, m in nested:
                out.append("        self.%s.write(mem, ptr.wrapping_add(%d))?;" % (name, m.offset))
            out.append("        Ok(())\n    }\n}")
        out.append("")
    return "\n".join(out) + "\n"


# -- event records -------------------------------------------------------------

def record_field(spec, m):
    """(rust name, rust type, kind) of a record member; kind is how it is stored."""
    t = m.ty
    if t.kind == "prim" and t.base == "event_string":
        return snake(m.name), "String", "string"
    if t.kind == "enum" and t.open:
        return snake(m.name), "u32", "scalar"
    if t.kind == "enum":
        return snake(m.name), pascal(t.base), "enum"
    if t.kind == "struct":
        return snake(m.name), pascal(t.base), "struct"
    return snake(m.name), scalar(spec, t), "scalar"


def emit_events(spec):
    out = [BANNER]
    out.append("use super::enums::*;")
    out.append("use super::structs::*;")
    out.append("#[allow(unused_imports)]")
    out.append("use super::{rd_u32, rd_u64, wr_u32, wr_u64, AbiEnum, Handle};\n")
    out.append("/// Bytes every record starts with.")
    out.append("pub const HEADER_SIZE: usize = %d;\n" % HEADER_SIZE)
    offsets = dict((m.name, m.offset) for m in spec.header.members)
    out.append("/// `WGUIEventHeader`, without the two fields the record itself decides (its size and type).")
    out.append("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]")
    out.append("pub struct EventHeader {")
    out.append("    pub flags: u32,\n    pub window: Handle,\n    pub timestamp: u64,\n    pub device: u32,\n    pub sequence: u32,")
    out.append("}\n")
    out.append("impl EventHeader {")
    out.append("    fn store(&self, b: &mut [u8], size: u32, ty: EventType) {")
    out.append("        wr_u32(b, %d, size);" % offsets["size"])
    out.append("        wr_u32(b, %d, ty.as_u32());" % offsets["type"])
    out.append("        wr_u32(b, %d, self.flags);" % offsets["flags"])
    out.append("        wr_u32(b, %d, self.window);" % offsets["window"])
    out.append("        wr_u64(b, %d, self.timestamp);" % offsets["timestamp"])
    out.append("        wr_u32(b, %d, self.device);" % offsets["device"])
    out.append("        wr_u32(b, %d, self.sequence);" % offsets["sequence"])
    out.append("    }")
    out.append("    fn load(b: &[u8]) -> Self {")
    out.append("        Self {")
    out.append("            flags: rd_u32(b, %d)," % offsets["flags"])
    out.append("            window: rd_u32(b, %d)," % offsets["window"])
    out.append("            timestamp: rd_u64(b, %d)," % offsets["timestamp"])
    out.append("            device: rd_u32(b, %d)," % offsets["device"])
    out.append("            sequence: rd_u32(b, %d)," % offsets["sequence"])
    out.append("        }\n    }\n}\n")

    out.append("/// Appends `text` to a record being built and stores where it went. An empty string is stored as absent.")
    out.append("fn put_string(b: &mut Vec<u8>, at: usize, text: &str) {")
    out.append("    if text.is_empty() {\n        return;\n    }")
    out.append("    let offset = b.len() as u32;")
    out.append("    b.extend_from_slice(text.as_bytes());")
    out.append("    wr_u32(b, at, offset);")
    out.append("    wr_u32(b, at + 4, text.len() as u32);")
    out.append("}\n")
    out.append("/// The string a record stores at `at`, if it lies inside the record and is UTF-8.")
    out.append("fn get_string(b: &[u8], fixed: usize, at: usize) -> Option<String> {")
    out.append("    let (offset, length) = (rd_u32(b, at) as usize, rd_u32(b, at + 4) as usize);")
    out.append("    if offset == 0 {\n        return (length == 0).then(String::new);\n    }")
    out.append("    if offset < fixed || offset > b.len() || length > b.len() - offset {\n        return None;\n    }")
    out.append("    std::str::from_utf8(&b[offset..offset + length]).ok().map(str::to_owned)")
    out.append("}\n")

    for r in spec.records:
        fields = [record_field(spec, m) + (m,) for m in r.members]
        visible = [f for f in fields if not f[0].startswith("reserved")]
        out.append("/// `%s`: %d bytes before its strings." % (r.c_name, r.size))
        derive = "Clone, Debug, Default, PartialEq"
        out.append("#[derive(%s)]" % derive)
        out.append("pub struct %s {" % r.rust_name)
        for name, t, _, _ in visible:
            out.append("    pub %s: %s," % (name, t))
        out.append("}")
        out.append("impl %s {" % r.rust_name)
        out.append("    pub const SIZE: usize = %d;" % r.size)
        out.append("    fn store(&self, b: &mut Vec<u8>) {")
        for name, t, kind, m in visible:
            o = m.offset
            if kind == "string":
                out.append("        put_string(b, %d, &self.%s);" % (o, name))
            elif kind == "enum":
                out.append("        wr_u32(b, %d, self.%s.as_u32());" % (o, name))
            elif kind == "struct":
                nested = spec.struct_by_name[m.ty.base]
                for nm in nested.members:
                    stmt = STORE[scalar(spec, nm.ty)][2] % (o + nm.offset, "self.%s.%s" % (name, snake(nm.name)))
                    out.append("        " + stmt.replace("&mut b", "b"))
            else:
                out.append("        " + (STORE[t][2] % (o, "self." + name)).replace("&mut b", "b"))
        out.append("    }")
        out.append("    fn load(b: &[u8]) -> Option<Self> {")
        out.append("        Some(Self {")
        for name, t, kind, m in visible:
            o = m.offset
            if kind == "string":
                out.append("            %s: get_string(b, Self::SIZE, %d)?," % (name, o))
            elif kind == "enum":
                out.append("            %s: %s::from_u32(rd_u32(b, %d))?," % (name, t, o))
            elif kind == "struct":
                nested = spec.struct_by_name[m.ty.base]
                out.append("            %s: %s {" % (name, t))
                for nm in nested.members:
                    expr = STORE[scalar(spec, nm.ty)][1] % (o + nm.offset)
                    out.append("                %s: %s," % (snake(nm.name), expr.replace("&b", "b")))
                out.append("            },")
            else:
                out.append("            %s: %s," % (name, (STORE[t][1] % o).replace("&b", "b")))
        out.append("        })\n    }\n}\n")

    out.append("/// One event, as the host holds it before it becomes a record in a guest's buffer.")
    out.append("#[derive(Clone, Debug, PartialEq)]")
    out.append("pub enum Event {")
    for e in spec.events:
        if e.record:
            out.append("    %s(%s)," % (pascal(e.name), spec.struct_by_name[e.record].rust_name))
        else:
            out.append("    %s," % pascal(e.name))
    out.append("}\n")
    out.append("impl Event {")
    out.append("    pub fn ty(&self) -> EventType {")
    out.append("        match self {")
    for e in spec.events:
        out.append("            Self::%s%s => EventType::%s," % (pascal(e.name), "(_)" if e.record else "", pascal(e.name)))
    out.append("        }\n    }\n")
    out.append("    /// The bit of this event's class in a `WGUIEventClass` mask.")
    out.append("    pub fn class(&self) -> u64 {")
    out.append("        1 << (self.ty().as_u32() >> 8)")
    out.append("    }\n")
    out.append("    /// Appends this event to `out` as one record, padded to 8 bytes, and returns the record's size.")
    out.append("    pub fn encode(&self, header: &EventHeader, out: &mut Vec<u8>) -> usize {")
    out.append("        let fixed = match self {")
    for e in spec.events:
        if e.record:
            out.append("            Self::%s(_) => %s::SIZE," % (pascal(e.name), spec.struct_by_name[e.record].rust_name))
        else:
            out.append("            Self::%s => HEADER_SIZE," % pascal(e.name))
    out.append("        };")
    out.append("        let mut b = vec![0u8; fixed];")
    out.append("        match self {")
    for e in spec.events:
        if e.record:
            out.append("            Self::%s(record) => record.store(&mut b)," % pascal(e.name))
    plain = [pascal(e.name) for e in spec.events if not e.record]
    out.append("            %s => {}" % "\n            | ".join("Self::" + p for p in plain))
    out.append("        }")
    out.append("        b.resize(b.len().next_multiple_of(8), 0);")
    out.append("        let size = b.len();")
    out.append("        header.store(&mut b, size as u32, self.ty());")
    out.append("        out.extend_from_slice(&b);")
    out.append("        size")
    out.append("    }\n")
    out.append("    /// Decodes the record at the start of `bytes`: its header, the event, and its size.")
    out.append("    ///")
    out.append("    /// `None` for anything a host would not have written: a size that does not fit,")
    out.append("    /// a type or an enum value this version does not know, a string outside the record.")
    out.append("    pub fn decode(bytes: &[u8]) -> Option<(EventHeader, Self, usize)> {")
    out.append("        if bytes.len() < HEADER_SIZE {\n            return None;\n        }")
    out.append("        let size = rd_u32(bytes, %d) as usize;" % offsets["size"])
    out.append("        if size < HEADER_SIZE || size > bytes.len() || size % 8 != 0 || size > MAX_EVENT_SIZE as usize {")
    out.append("            return None;\n        }")
    out.append("        let b = &bytes[..size];")
    out.append("        let ty = EventType::from_u32(rd_u32(b, %d))?;" % offsets["type"])
    out.append("        let fits = |fixed: usize| (size >= fixed).then_some(());")
    out.append("        let event = match ty {")
    for e in spec.events:
        if e.record:
            rn = spec.struct_by_name[e.record].rust_name
            out.append("            EventType::%s => {" % pascal(e.name))
            out.append("                fits(%s::SIZE)?;" % rn)
            out.append("                Self::%s(%s::load(b)?)" % (pascal(e.name), rn))
            out.append("            }")
        else:
            out.append("            EventType::%s => Self::%s," % (pascal(e.name), pascal(e.name)))
    out.append("        };")
    out.append("        Some((EventHeader::load(b), event, size))")
    out.append("    }\n}")
    return "\n".join(out) + "\n"


# -- API traits and import glue ---------------------------------------------------

class Lowered(object):
    """How one C parameter appears in the wasm signature, the glue, and the trait."""

    def __init__(self, wasm, prelude, trait_ty, call):
        self.wasm = wasm  # [(name, rust wasm type)]
        self.prelude = prelude  # statements run before the call (may use `?`)
        self.trait_ty = trait_ty  # type in the trait method signature
        self.call = call  # expression passed to the trait method


def pointee(spec, a):
    """Rust type an out-pointer to this scalar stores."""
    if a.kind == "prim":
        return {"uint64": "u64", "float64": "f64"}.get(a.base, "u32")
    if a.kind == "bitflag":
        return flag_type(spec, a.base)
    return "u32"  # enums and handles


def lower_arg(spec, a):
    n = snake(a.name)
    required = [] if a.optional else ["if %s == 0 {\n            return Err(AbiError::NullPointer(\"%s\"));\n        }" % (
        n, a.name)]
    if a.array:
        cn = snake(singular(a.name)) + "_count"
        wasm = [(cn, "u32"), (n, "u32")]
        t = pascal(a.base)
        reader = "read_array" if a.kind == "struct" else "read_enum_array"
        return Lowered(wasm, ["let %s = cx.mem.%s::<%s>(%s, %s)?;" % (n, reader, t, n, cn)], "&[%s]" % t, "&" + n)
    if a.kind == "string":
        ln = n + "_length"
        return Lowered([(n, "u32"), (ln, "u32")], ["let %s = cx.mem.read_string(%s, %s)?;" % (n, n, ln)], "&str", "&" + n)
    if a.kind == "struct":
        t = pascal(a.base)
        if a.pointer == "mutable":
            return Lowered([(n, "u32")], required, "OutPtr<%s>" % t, "OutPtr::new(%s)" % n)
        if a.optional:
            return Lowered([(n, "u32")], ["let %s = cx.mem.read_opt::<%s>(%s)?;" % (n, t, n)],
                           "Option<&%s>" % t, n + ".as_ref()")
        return Lowered([(n, "u32")], ["let %s = cx.mem.read_required::<%s>(%s, \"%s\")?;" % (n, t, n, a.name)],
                       "&%s" % t, "&" + n)
    if a.pointer:
        if a.kind == "void" or (a.kind == "prim" and a.base == "char"):
            return Lowered([(n, "u32")], required, "u32", n)  # a buffer: the implementation knows its length
        return Lowered([(n, "u32")], required, "OutPtr<%s>" % pointee(spec, a), "OutPtr::new(%s)" % n)
    if a.kind == "object":
        return Lowered([(n, "u32")], [], "Handle", n)
    if a.kind == "enum":
        t = pascal(a.base)
        return Lowered([(n, "u32")], ["let %s = %s::from_abi(%s)?;" % (n, t, n)], t, n)
    if a.kind == "bitflag":
        t = flag_type(spec, a.base)
        return Lowered([(n, t)], [], t, n)
    if a.kind == "prim":
        t = RUST_PRIM[a.base]
        if a.base == "bool":
            return Lowered([(n, "u32")], [], "bool", n + " != 0")
        return Lowered([(n, t)], [], t, n)
    raise SystemExit("cannot lower argument " + a.raw)


RETURNS = {
    # spec result -> (wasm result, trait return type)
    None: ("()", "()"),
    "status": ("u32", "AbiResult<Status>"),
    "uint32": ("u32", "u32"),
    "bool": ("u32", "bool"),
}


def emit_api(spec):
    """One trait per object, the glue that decodes wasm arguments for them, and the registration."""
    out = [BANNER]
    out.append("use wasmer::{AsStoreMut, Exports, Function, FunctionEnv, FunctionEnvMut, RuntimeError};\n")
    out.append("use super::enums::*;\nuse super::structs::*;")
    out.append("#[allow(unused_imports)]")
    out.append("use super::{AbiEnum, AbiError, AbiResult, Cx, Handle, OutPtr};")
    out.append("use crate::env::GuiEnv;\nuse crate::host::{enter, let_signals_in};\n")

    traits, order = {}, []
    glue, reg, arms = [], [], []
    widest = [0]

    def trait_of(owner):
        name = (pascal(owner) if owner else "Global") + "Api"
        if name not in traits:
            traits[name] = []
            order.append(name)
        return traits[name]

    for fn in spec.functions:
        params, prelude, sig, call = [], [], [], []
        if fn.owner is not None:
            recv = snake(fn.owner)
            params.append((recv, "u32"))
            sig.append("%s: Handle" % recv)
            call.append(recv)
        for a in fn.args:
            low = lower_arg(spec, a)
            params += low.wasm
            prelude += low.prelude
            sig.append("%s: %s" % (snake(a.name), low.trait_ty))
            call.append(low.call)
        wasm_ret, trait_ret = RETURNS[fn.returns]

        methods = trait_of(fn.owner)
        methods.append("    /// `%s`" % fn.c_name)
        methods.append("    fn %s(&self, cx: &mut Cx<'_>%s)%s;" % (
            fn.rust_name, "".join(", " + s for s in sig), "" if trait_ret == "()" else " -> " + trait_ret))

        glue_name = "import_" + fn.rust_name
        args = "".join(", %s: %s" % p for p in params)
        glue.append("fn %s(mut env: FunctionEnvMut<'_, GuiEnv>%s) -> Result<%s, RuntimeError> {" % (
            glue_name, args, wasm_ret))
        # Where the host lets the program's signals in. A call that may block
        # does once it is over, so that what a handler changed is what the
        # program finds when the call returns; one that is made every frame
        # does first, now and then.
        after = fn.signals and fn.blocking
        if fn.signals and not after:
            glue.append("    let_signals_in(&mut env, false)?;")
        glue.append("    %senter(&mut env, \"%s\", |host, cx| {" % ("let returned = " if after else "", fn.c_name))
        for p in prelude:
            glue.append("        " + p)
        invoke = "host.%s(cx%s)" % (fn.rust_name, "".join(", " + c for c in call))
        if fn.returns == "status":
            glue.append("        %s" % invoke)
        else:
            glue.append("        Ok(%s)" % invoke)
        if after:
            glue.append("    })?;")
            glue.append("    let_signals_in(&mut env, true)?;")
            glue.append("    Ok(returned)\n}\n")
        else:
            glue.append("    })\n}\n")
        reg.append("    exports.insert(\"%s\", Function::new_typed_with_env(store, env, %s));" % (fn.c_name, glue_name))
        getters = {
            "u32": "raw[%d] as u32", "i32": "raw[%d] as u32 as i32",
            "u64": "raw[%d]", "i64": "raw[%d] as i64",
            "f64": "f64::from_bits(raw[%d])",
        }
        widest[0] = max(widest[0], len(params))
        passed = "".join(", " + getters[ty] % at for at, (_, ty) in enumerate(params))
        result = {"u32": "value(%s)", "()": "nothing(%s)"}[wasm_ret]
        arms.append("        %d => %s," % (len(arms), result % ("%s(env%s)" % (glue_name, passed))))

    out.append("// One trait per object, so that each is implemented in its own file. Arguments")
    out.append("// arrive decoded from the guest's wasm32 layout; pointers the guest must pass")
    out.append("// have been checked for null. A missing method is a compile error, which is")
    out.append("// what keeps the host complete.\n")
    for name in order:
        out.append("/// The %s functions of `gui.h`." % ("global" if name == "GlobalApi" else "`" + PREFIX + name[:-3] + "`"))
        out.append("pub trait %s {" % name)
        out += traits[name]
        out.append("}\n")
    out.append("/// Everything the host implements for the guest.")
    out.append("pub trait Api:\n    " + "\n    + ".join(order) + "\n{\n}")
    out.append("impl<T> Api for T where\n    T: " + "\n        + ".join(order) + "\n{\n}\n")
    out.append("const _: fn() = || {\n    fn complete<T: Api>() {}\n    complete::<crate::host::Host>();\n};\n")
    out += glue
    out.append("/// Registers every import of the `%s` module." % spec.import_module)
    out.append("#[cfg(not(target_arch = \"wasm32\"))]")
    out.append("pub(crate) fn register(store: &mut impl AsStoreMut, env: &FunctionEnv<GuiEnv>, exports: &mut Exports) {")
    out += reg
    out.append("}\n")
    typed = [fn for fn in spec.functions if fn.signals]
    out.append("/// The same where the embedder is itself WebAssembly. There a typed function")
    out.append("/// brings a wrapper of its own into the embedder's module, a few kilobytes for")
    out.append("/// each import. So one function serves them all, told which import it is by")
    out.append("/// that import's place in `IMPORTS`.")
    out.append("///")
    out.append("/// All but the imports where the system reaches the program: what ends a")
    out.append("/// program there is the runtime's own error, which has to arrive as what it")
    out.append("/// is, and the one function for all reports a failure as its text.")
    out.append("#[cfg(target_arch = \"wasm32\")]")
    out.append("pub(crate) fn register(store: &mut impl AsStoreMut, env: &FunctionEnv<GuiEnv>, exports: &mut Exports) {")
    out.append("    use super::ValType;")
    out.append("    let wasm = |types: &[ValType]| -> Vec<wasmer::Type> {")
    out.append("        types")
    out.append("            .iter()")
    out.append("            .map(|ty| match ty {")
    out.append("                ValType::I32 => wasmer::Type::I32,")
    out.append("                ValType::I64 => wasmer::Type::I64,")
    out.append("                ValType::F32 => wasmer::Type::F32,")
    out.append("                ValType::F64 => wasmer::Type::F64,")
    out.append("            })")
    out.append("            .collect()")
    out.append("    };")
    out.append("    for (index, sig) in super::IMPORTS.iter().enumerate() {")
    out.append("        if matches!(sig.name, %s) {" % " | ".join('"%s"' % fn.c_name for fn in typed))
    out.append("            continue;")
    out.append("        }")
    out.append("        let ty = wasmer::FunctionType::new(wasm(sig.params), wasm(sig.results));")
    out.append("        let function = Function::new_with_env(store, env, ty, move |env, args| call(index, env, args));")
    out.append("        exports.insert(sig.name, function);")
    out.append("    }")
    for fn in typed:
        out.append("    exports.insert(\"%s\", Function::new_typed_with_env(store, env, import_%s));" % (fn.c_name, fn.rust_name))
    out.append("}\n")
    out.append("#[cfg(target_arch = \"wasm32\")]")
    out.append("fn call(index: usize, env: FunctionEnvMut<'_, GuiEnv>, args: &[wasmer::Value]) -> Result<Vec<wasmer::Value>, RuntimeError> {")
    out.append("    use wasmer::Value;")
    out.append("    // The engine checked the arguments against the import's type. Here they")
    out.append("    // are taken apart once, as bits, for whichever import this is.")
    out.append("    let mut raw = [0_u64; %d];" % widest[0])
    out.append("    for (bits, value) in raw.iter_mut().zip(args) {")
    out.append("        *bits = match value {")
    out.append("            Value::I32(value) => u64::from(*value as u32),")
    out.append("            Value::I64(value) => *value as u64,")
    out.append("            Value::F64(value) => value.to_bits(),")
    out.append("            _ => 0,")
    out.append("        };")
    out.append("    }")
    out.append("    let value = |result: Result<u32, RuntimeError>| result.map(|value| vec![Value::I32(value as i32)]);")
    out.append("    let nothing = |result: Result<(), RuntimeError>| result.map(|()| Vec::new());")
    out.append("    match index {")
    out += arms
    out.append("        _ => Err(RuntimeError::new(\"no such import\")),")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


# -- import signature table -------------------------------------------------------

def emit_imports(spec):
    out = [BANNER]
    out.append("use super::{ImportSig, ValType::*};\n")
    out.append("pub const IMPORT_MODULE: &str = \"%s\";\n" % spec.import_module)
    out.append("/// Name and core wasm signature of every import, in the order of the header.")
    out.append("pub static IMPORTS: &[ImportSig] = &[")
    for fn in spec.functions:
        params = [t for _, t in spec.lower_params(fn)]
        result = spec.lower_result(fn)
        out.append("    ImportSig { name: \"%s\", params: &[%s], results: &[%s], blocking: %s }," % (
            fn.c_name, ", ".join(p.upper() for p in params), result.upper() if result else "",
            "true" if fn.blocking else "false"))
    out.append("];")
    return "\n".join(out) + "\n"
