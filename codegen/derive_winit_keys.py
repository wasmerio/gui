#!/usr/bin/env python3
"""Derives the key tables between winit and this API from winit's key enums:
src/native/keys.rs, for the host that opens native windows through winit, and
integrations/winit/backend/keys.rs, for winit's own backend on this API.

    python3 codegen/derive_winit_keys.py <winit checkout>/src/keyboard.rs

winit names physical keys and named keys the way the W3C UI Events tables do,
which is how spec/keys.json names them, so the conversion is a table of equal
names with the few exceptions listed here. Run it again when the winit version
this crate builds against gains keys; a name this crate has no key for is an
error, to be settled in spec/keys.json first.
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from spec import ROOT, Spec, screaming  # noqa: E402

# winit's own names, where they are not the W3C `code`.
PHYSICAL = {
    "SuperLeft": "MetaLeft",
    "SuperRight": "MetaRight",
    # "Legacy modifier key. Also called 'Super' in certain places."
    "Meta": "Super",
    # Keys winit tells apart that share a USB usage with these.
    "Hiragana": "Lang4",
    "Katakana": "Lang3",
}
# winit's own names, where they are not the W3C `key`.
NAMED = {
    "Super": "Meta",
    "Meta": "Super",
}


def variants(source, enum):
    body = re.search(r"pub enum %s \{(.*?)\n\}" % enum, source, re.S).group(1)
    return re.findall(r"^\s{4}([A-Z][A-Za-z0-9]*),", body, re.M)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    with open(sys.argv[1]) as f:
        source = f.read()
    spec = Spec()
    physical = set(name for name, _ in spec.physical_keys)
    named = set(name for name, _ in spec.named_keys)

    out = ["//! winit's names for keys, as this API's.",
           "//!",
           "//! Generated by codegen/derive_winit_keys.py from winit's `src/keyboard.rs`.",
           "//! Do not edit.",
           "",
           "use winit::keyboard::{KeyCode, NamedKey};",
           "",
           "use crate::abi::enums::{PhysicalKey, key};",
           "",
           "/// The physical key winit calls `code`.",
           "pub(super) fn physical_key(code: KeyCode) -> PhysicalKey {",
           "    match code {"]
    missing = []
    for variant in variants(source, "KeyCode"):
        ours = PHYSICAL.get(variant, variant)
        if ours not in physical:
            missing.append("KeyCode::" + variant)
            continue
        out.append("        KeyCode::%s => PhysicalKey::%s," % (variant, ours))
    out += ["        _ => PhysicalKey::Unidentified,", "    }", "}", "",
            "/// The `WGUIKey` of the key winit calls `named`. The space bar is a named",
            "/// key to winit and the character it types here.",
            "pub(super) fn named_key(named: NamedKey) -> u32 {",
            "    match named {"]
    for variant in variants(source, "NamedKey"):
        if variant == "Space":
            out.append("        NamedKey::Space => 0x20,")
            continue
        ours = NAMED.get(variant, variant)
        if ours not in named:
            missing.append("NamedKey::" + variant)
            continue
        out.append("        NamedKey::%s => key::%s," % (variant, screaming(ours)))
    out += ["        _ => key::UNIDENTIFIED,", "    }", "}", ""]
    if missing:
        raise SystemExit("no key in spec/keys.json for: " + ", ".join(missing))
    path = os.path.join(ROOT, "src", "native", "keys.rs")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("wrote src/native/keys.rs")

    # The other way, for winit's backend on this API. Where winit has two
    # names for what is one key here, the one that is also this API's wins.
    back = ["//! This API's keys, as winit's.",
            "//!",
            "//! Generated by codegen/derive_winit_keys.py (in wasmer-gui) from winit's",
            "//! `src/keyboard.rs`. Do not edit.",
            "",
            "use wasmer_gui_sys::*;",
            "",
            "use crate::keyboard::{KeyCode, NamedKey};",
            "",
            "/// The key winit calls by the name the host has for a physical key.",
            "pub(super) fn key_code(key: WGUIPhysicalKey) -> Option<KeyCode> {",
            "    Some(match key {"]
    codes = variants(source, "KeyCode")
    taken = set()
    for variant in sorted(codes, key=lambda v: PHYSICAL.get(v, v) != v):
        ours = PHYSICAL.get(variant, variant)
        if ours in taken:
            continue
        taken.add(ours)
        back.append("        WGUIPhysicalKey_%s => KeyCode::%s," % (ours, variant))
    back += ["        _ => return None,", "    })", "}", "",
             "/// The key winit calls by the name the host has for a named key.",
             "pub(super) fn named_key(key: WGUIKey) -> Option<NamedKey> {",
             "    Some(match key {"]
    taken = set()
    for variant in sorted(variants(source, "NamedKey"), key=lambda v: NAMED.get(v, v) != v):
        if variant == "Space":
            continue
        ours = NAMED.get(variant, variant)
        if ours in taken:
            continue
        taken.add(ours)
        back.append("        WGUIKey_%s => NamedKey::%s," % (ours, variant))
    back += ["        _ => return None,", "    })", "}", ""]
    path = os.path.join(ROOT, "integrations", "winit", "backend", "keys.rs")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(back))
    print("wrote integrations/winit/backend/keys.rs")


if __name__ == "__main__":
    main()
