"""Guest-side C outputs: the header, and the programs that check it."""

import textwrap

from spec import FN_PREFIX, HEADER_SIZE, PREFIX, PRIMS, camel, pascal, singular

BANNER = "// Generated by codegen/gen.py from spec/gui.json and spec/keys.json. Do not edit.\n"
WIDTH = 96


def comment(text, indent=""):
    """A doc comment for `text`, or nothing when there is nothing to say.

    Paragraphs are separated by blank lines and wrapped; a paragraph whose
    lines all start with four spaces is code and is kept as written.
    """
    if not text.strip():
        return []
    lines = []
    for paragraph in text.strip("\n").split("\n\n"):
        if lines:
            lines.append("")
        rows = paragraph.split("\n")
        if all(row.startswith("    ") for row in rows):
            lines += [row.rstrip() for row in rows]
        else:
            lines += textwrap.wrap(" ".join(paragraph.split()), WIDTH - len(indent) - 3)
    if len(lines) == 1:
        return ["%s/** %s */" % (indent, lines[0])]
    return [indent + "/**"] + [(indent + " * " + line).rstrip() for line in lines] + [indent + " */"]


def literal(spec, ctype, value):
    """A C expression for a constant of the spec."""
    named = {
        "version": "0x%08XU" % spec.version,
        "usize_max": "SIZE_MAX",
        "uint32_max": "UINT32_MAX",
        "uint64_max": "UINT64_MAX",
        "int32_min": "INT32_MIN",
    }
    if value in named:
        return named[value]
    if ctype == "uint32" and value.lower().startswith("0x"):
        return value + "U"
    return value


def flag_literal(flag, value):
    return "0x%0*X" % (flag.width // 4, value)


def member_decl(spec, m):
    """[(c type, c name)] of a struct member: arrays are a count and a pointer."""
    if m.ty.array:
        return [("size_t", m.c_count_name), ("const " + spec.c_base(m.ty) + "*", m.c_name)]
    return [(spec.c_type(m.ty), m.c_name)]


def member_default(spec, m):
    """The C initializer of a struct member in its INIT macro."""
    t = m.ty
    if t.array:
        return ["0", "NULL"]
    if t.pointer:
        return ["NULL"]
    if t.kind == "string":
        return [PREFIX + "_STRING_VIEW_INIT"]
    if t.kind == "struct":
        return [spec.struct_by_name[t.base].init_name]
    if t.kind == "bitflag":
        flag = spec.bitflag_by_name[t.base]
        names = t.default or []
        if not isinstance(names, list):
            names = [names]
        value = 0
        for n in names:
            value |= flag.value(n)
        # Spelled as a number: a `static const` is not a constant expression in C.
        text = flag_literal(flag, value)
        if names:
            text += " /* %s */" % " | ".join(pascal(n) for n in names)
        return [text]
    if t.kind == "enum":
        enum = spec.enum_by_name[t.base]
        if t.default:
            return [spec.enum_entry_c(t.base, t.default)]
        zero = [n for n, v, _ in enum.entries if v == 0]
        return [spec.enum_entry_c(t.base, zero[0])] if zero else ["(%s)0" % enum.c_name]
    if t.default and str(t.default).startswith("constant."):
        return ["%s_%s" % (PREFIX, t.default.split(".", 1)[1].upper())]
    if t.default:
        return [str(t.default)]
    if t.kind == "prim" and t.base in ("float32", "float64"):
        return ["0.0"]
    return ["0"]


def emit_struct(spec, s, out):
    out += comment(s.doc)
    out.append("typedef struct %s {" % s.c_name)
    fields = []
    if s.kind == "extensible":
        fields.append(("%sChainedStruct*" % PREFIX, "nextInChain", "NULL", ""))
    elif s.kind == "extension":
        fields.append(("%sChainedStruct" % PREFIX, "chain", None, ""))
    elif s.kind == "record":
        fields.append(("%sEventHeader" % PREFIX, "header", None, ""))
    for m in s.members:
        decls = member_decl(spec, m)
        defaults = member_default(spec, m)
        for i, ((ctype, cname), default) in enumerate(zip(decls, defaults)):
            fields.append((ctype, cname, default, m.doc if i == len(decls) - 1 or len(decls) == 1 else ""))
    for ctype, cname, _, doc in fields:
        out += comment(doc, "    ")
        out.append("    %s %s;" % (ctype, cname))
    out.append("} %s;" % s.c_name)
    if s.kind in ("extensible", "standalone"):
        out.append("")
        out.append("#define %s %s_MAKE_INIT_STRUCT(%s, { \\" % (s.init_name, PREFIX, s.c_name))
        for i, (_, cname, default, _) in enumerate(fields):
            sep = " %s_COMMA" % PREFIX if i + 1 < len(fields) else ""
            out.append("    /*.%s=*/%s%s \\" % (cname, default, sep))
        out.append("})")
    out.append("")


def emit_header(spec):
    P = PREFIX
    out = [BANNER.rstrip()]
    out.append("")
    out += comment("<wasmer/gui.h>\n\n" + spec.doc)
    out.append("")
    out.append("#ifndef WASMER_GUI_H_")
    out.append("#define WASMER_GUI_H_")
    out.append("")
    out.append("#include <stddef.h>")
    out.append("#include <stdint.h>")
    out.append("")
    out += comment("Every function below is a WebAssembly import of this module: there is no library to link.")
    out.append("#define %s_IMPORT_MODULE \"%s\"" % (P, spec.import_module))
    out.append("#if defined(__wasm__)")
    out.append("#  define %s_IMPORT(name) __attribute__((import_module(%s_IMPORT_MODULE), import_name(#name)))" % (P, P))
    out.append("#else")
    out.append("#  define %s_IMPORT(name)" % P)
    out.append("#endif")
    out.append("")
    out.append("#if defined(__cplusplus)")
    out.append("#  define %s_COMMA ," % P)
    out.append("#  if __cplusplus >= 201103L")
    out.append("#    define %s_MAKE_INIT_STRUCT(type, value) (type value)" % P)
    out.append("#  else")
    out.append("#    define %s_MAKE_INIT_STRUCT(type, value) value" % P)
    out.append("#  endif")
    out.append("#elif defined(__STDC_VERSION__) && __STDC_VERSION__ >= 199901L")
    out.append("#  define %s_COMMA ," % P)
    out.append("#  define %s_MAKE_INIT_STRUCT(type, value) ((type) value)" % P)
    out.append("#else")
    out.append("#  define %s_COMMA ," % P)
    out.append("#  define %s_MAKE_INIT_STRUCT(type, value) value" % P)
    out.append("#endif")
    out.append("")

    out.append("// -- Constants " + "-" * 60)
    out.append("")
    for name, ctype, value, doc in spec.constants:
        out += comment(doc)
        out.append("#define %s_%s (%s)" % (P, name.upper(), literal(spec, ctype, value)))
        out.append("")

    out.append("// -- Basic types " + "-" * 58)
    out.append("")
    out.append("typedef uint32_t %sBool;" % P)
    out += comment("Sets of flags that have room for 64.")
    out.append("typedef uint64_t %sFlags;" % P)
    out.append("")
    out.append("// Handles are numbers the host gives out. 0 is never a handle. A handle works on")
    out.append("// every thread of the program, and using one after it was destroyed is an error")
    out.append("// the host reports, not a crash.")
    out.append("")
    for name, doc in spec.objects:
        out += comment(doc)
        out.append("typedef uint32_t %s%s;" % (P, pascal(name)))
        out.append("")
    out += comment("A string that need not end in NUL: `length` bytes at `data`, or up to the first NUL when `length` "
                   "is WGUI_STRLEN. UTF-8.")
    out.append("typedef struct %sStringView {" % P)
    out.append("    const char* data;")
    out.append("    size_t length;")
    out.append("} %sStringView;" % P)
    out.append("")
    out.append("#define %s_STRING_VIEW_INIT %s_MAKE_INIT_STRUCT(%sStringView, { \\" % (P, P, P))
    out.append("    /*.data=*/NULL %s_COMMA \\" % P)
    out.append("    /*.length=*/%s_STRLEN \\" % P)
    out.append("})")
    out.append("")

    out.append("// -- Enumerations " + "-" * 57)
    out.append("")
    for e in spec.enums:
        out += comment(e.doc)
        out.append("typedef enum %s {" % e.c_name)
        for name, value, doc in e.entries:
            if e.name == "event_type":
                event = [ev for ev in spec.events if ev.name == name][0]
                record = "Record: %s." % spec.struct_by_name[event.record].c_name if event.record else "Header only."
                doc = (doc + " " if doc else "") + record
            out += comment(doc, "    ")
            out.append("    %s = 0x%08X," % (spec.enum_entry_c(e.name, name), value))
        out.append("    %s_Force32 = 0x7FFFFFFF" % e.c_name)
        out.append("} %s;" % e.c_name)
        out.append("")

    out.append("// -- Flags " + "-" * 64)
    out.append("")
    for b in spec.bitflags:
        out += comment(b.doc)
        out.append("typedef %s %s;" % ("%sFlags" % P if b.width == 64 else "uint32_t", b.c_name))
        for name, value, doc in b.entries:
            out += comment(doc)
            out.append("static const %s %s = %s;" % (b.c_name, b.c_entry(name), flag_literal(b, value)))
        out.append("")

    out.append("// -- Keys " + "-" * 65)
    out.append("")
    out += comment(
        "What a key means on the user's layout: the KeyboardEvent `key` of the W3C UI Events specification, as a "
        "number. The top byte is a tag (WGUI_KEY_TAG) and the rest its value (WGUI_KEY_VALUE):\n\n"
        "WGUI_KEY_CHARACTER: the Unicode scalar value the key produces, so 'a' is 0x61. 0 is WGUIKey_Unidentified.\n\n"
        "WGUI_KEY_NAMED: one of the WGUIKey_* constants below.\n\n"
        "WGUI_KEY_DEAD: a dead key; the value is the combining character it adds, or 0.\n\n"
        "WGUI_KEY_SEQUENCE: more than one scalar value; the value is the first and the event's keyString has all.")
    out.append("typedef uint32_t %sKey;" % P)
    out.append("#define %s_KEY_TAG(key) ((key) & %s_KEY_TAG_MASK)" % (P, P))
    out.append("#define %s_KEY_VALUE(key) ((key) & %s_KEY_VALUE_MASK)" % (P, P))
    out.append("")
    out += comment("The named keys. (An enum rather than constants so that they work as `case` labels.)")
    out.append("enum {")
    out.append("    %sKey_Unidentified = 0x00000000," % P)
    for i, (name, value) in enumerate(spec.named_keys):
        out.append("    %sKey_%s = 0x%08X%s" % (P, name, 0x01000000 | value, "," if i + 1 < len(spec.named_keys) else ""))
    out.append("};")
    out.append("")

    out.append("// -- Structures " + "-" * 59)
    out.append("")
    out += comment("The start of a struct that extends another through its nextInChain list. Hosts skip structs they "
                   "do not know, unless the sType has WGUI_STYPE_MUST_UNDERSTAND set.")
    out.append("typedef struct %sChainedStruct {" % P)
    out.append("    struct %sChainedStruct* next;" % P)
    out.append("    %sSType sType;" % P)
    out.append("} %sChainedStruct;" % P)
    out.append("")
    for s in spec.structs:
        emit_struct(spec, s, out)

    out.append("// -- Event records " + "-" * 56)
    out.append("")
    out += comment(spec.header.doc)
    out.append("typedef struct %s {" % spec.header.c_name)
    for m in spec.header.members:
        out += comment(m.doc, "    ")
        out.append("    %s %s;" % (spec.c_type(m.ty), m.c_name))
    out.append("} %s;" % spec.header.c_name)
    out.append("")
    out += comment("A string inside an event record: `length` bytes of UTF-8 starting `offset` bytes from the start "
                   "of the record. An offset of 0 means there is no string. See wguiEventGetString.")
    out.append("typedef struct %sEventString {" % P)
    out.append("    uint32_t offset;")
    out.append("    uint32_t length;")
    out.append("} %sEventString;" % P)
    out.append("")
    for r in spec.records:
        emit_struct(spec, r, out)

    out.append("// -- Functions " + "-" * 60)
    out.append("")
    out.append("#ifdef __cplusplus")
    out.append("extern \"C\" {")
    out.append("#endif")
    out.append("")
    owner = object()
    for fn in spec.functions:
        if fn.owner != owner:
            owner = fn.owner
            out.append("// %s" % (P + pascal(owner) if owner else "Global"))
            out.append("")
        doc = fn.doc
        if fn.blocking:
            doc += "\n\nMay block."
        out += comment(doc)
        out.append("%s_IMPORT(%s)" % (P, fn.c_name))
        out.append(spec.c_decl(fn) + ";")
        out.append("")
    out.append("#ifdef __cplusplus")
    out.append("} // extern \"C\"")
    out.append("#endif")
    out.append("")

    out.append("// -- Reading events " + "-" * 55)
    out.append("")
    H = spec.header.c_name
    out += comment("The first record in a buffer that wguiInstancePollEvents filled with `written` bytes, or NULL "
                   "when there is none.\n\n"
                   "    uint64_t buffer[WGUI_MAX_EVENT_SIZE / 8];\n"
                   "    size_t written = 0;\n"
                   "    wguiInstancePollEvents(instance, buffer, sizeof buffer, &written);\n"
                   "    const WGUIEventHeader* event = wguiEventFirst(buffer, written);\n"
                   "    for (; event != NULL; event = wguiEventNext(buffer, written, event)) {\n"
                   "        switch (event->type) { ... }\n"
                   "    }")
    out.append("static inline const %s* %sEventFirst(const void* buffer, size_t written) {" % (H, FN_PREFIX))
    out.append("    const %s* event = (const %s*)buffer;" % (H, H))
    out.append("    if (written < sizeof(%s) || event->size < sizeof(%s) || event->size > written) {" % (H, H))
    out.append("        return NULL;")
    out.append("    }")
    out.append("    return event;")
    out.append("}")
    out.append("")
    out += comment("The record after `event` in the same buffer, or NULL at the end.")
    out.append("static inline const %s* %sEventNext(const void* buffer, size_t written, const %s* event) {" % (
        H, FN_PREFIX, H))
    out.append("    size_t next = (size_t)((const char*)event - (const char*)buffer) + event->size;")
    out.append("    if (next >= written) {")
    out.append("        return NULL;")
    out.append("    }")
    out.append("    return %sEventFirst((const char*)buffer + next, written - next);" % FN_PREFIX)
    out.append("}")
    out.append("")
    out += comment("A string of a record. It points into the record: copy it to keep it. An absent string has NULL "
                   "data and length 0.")
    out.append("static inline %sStringView %sEventGetString(const %s* event, %sEventString string) {" % (
        P, FN_PREFIX, H, P))
    out.append("    %sStringView view;" % P)
    out.append("    view.data = NULL;")
    out.append("    view.length = 0;")
    out.append("    if (string.offset >= sizeof(%s) && string.offset <= event->size" % H)
    out.append("        && string.length <= event->size - string.offset) {")
    out.append("        view.data = (const char*)event + string.offset;")
    out.append("        view.length = string.length;")
    out.append("    }")
    out.append("    return view;")
    out.append("}")
    out.append("")
    out.append("#endif // WASMER_GUI_H_")
    return "\n".join(out) + "\n"


def emit_names(spec):
    """An optional header: the names of the API's values, for logs and tools."""
    P = PREFIX
    out = [BANNER.rstrip()]
    out.append("")
    out += comment("<wasmer/gui_names.h>\n\nThe names of the values of <wasmer/gui.h>, for logs, tests and tools. "
                   "Nothing here is part of the API a host implements: these are plain functions compiled into the "
                   "program that includes this header.")
    out.append("")
    out.append("#ifndef WASMER_GUI_NAMES_H_")
    out.append("#define WASMER_GUI_NAMES_H_")
    out.append("")
    out.append("#include <wasmer/gui.h>")
    out.append("")
    for e in spec.enums:
        fn = "%s%sName" % (FN_PREFIX, pascal(e.name))
        out += comment("The name of a %s without its prefix (\"%s\"), or NULL for a value this header does not "
                       "know." % (e.c_name, spec.enum_entry_rust(e.name, e.entries[-1][0])))
        out.append("static inline const char* %s(%s value) {" % (fn, e.c_name))
        out.append("    switch ((uint32_t)value) {")
        for name, value, _ in e.entries:
            out.append("        case 0x%08X: return \"%s\";" % (value, spec.enum_entry_rust(e.name, name)))
        out.append("        default: return NULL;")
        out.append("    }")
        out.append("}")
        out.append("")
    out += comment("The name of a named WGUIKey (\"Enter\", \"ArrowLeft\"): its KeyboardEvent `key` value. NULL for "
                   "characters, dead keys, sequences and values this header does not know.")
    out.append("static inline const char* %sKeyName(%sKey key) {" % (FN_PREFIX, P))
    out.append("    switch (key) {")
    for name, value in spec.named_keys:
        out.append("        case 0x%08X: return \"%s\";" % (0x01000000 | value, name))
    out.append("        default: return NULL;")
    out.append("    }")
    out.append("}")
    out.append("")
    out += comment("How many flags of a set this header names, and the name and value of each: for printing a set "
                   "bit by bit.\n\n"
                   "    for (size_t i = 0; i < wguiModifiersCount(); i++) {\n"
                   "        if (modifiers & wguiModifiersValue(i)) puts(wguiModifiersName(i));\n"
                   "    }")
    out.append("#define %s_FLAG_NAMES(Type, count, ...) \\" % P)
    out.append("    static inline size_t %s##Type##Count(void) { return count; } \\" % FN_PREFIX)
    out.append("    static inline const char* %s##Type##Name(size_t index) { \\" % FN_PREFIX)
    out.append("        static const char* const names[] = {__VA_ARGS__}; \\")
    out.append("        return index < count ? names[index] : NULL; \\")
    out.append("    }")
    out.append("")
    for b in spec.bitflags:
        single = [(n, v) for n, v, _ in b.entries if v and v & (v - 1) == 0]
        T = pascal(b.name)
        out.append("%s_FLAG_NAMES(%s, %d, %s)" % (P, T, len(single), ", ".join('"%s"' % pascal(n) for n, _ in single)))
        out.append("static inline %s %s%sValue(size_t index) {" % (b.c_name, FN_PREFIX, T))
        out.append("    static const %s values[] = {%s};" % (b.c_name, ", ".join(flag_literal(b, v) for _, v in single)))
        out.append("    return index < %d ? values[index] : 0;" % len(single))
        out.append("}")
        out.append("")
    out.append("#endif // WASMER_GUI_NAMES_H_")
    return "\n".join(out) + "\n"


