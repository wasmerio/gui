def emit_abi_check(spec):
    """Static assertions that the header's layout is the one the host decodes."""
    P = PREFIX
    out = [BANNER]
    out.append("// Compile-only: the C compiler confirms every size, offset and value the")
    out.append("// generator computed for the host. A failed assertion means codegen/spec.py")
    out.append("// models the wasm32 C ABI wrongly.")
    out.append("")
    out.append("#include <stddef.h>")
    out.append("#include <wasmer/gui.h>")
    out.append("")
    out.append("#define SIZE(type, size, align) \\")
    out.append("    _Static_assert(sizeof(type) == size, #type \" size\"); \\")
    out.append("    _Static_assert(_Alignof(type) == align, #type \" alignment\")")
    out.append("#define OFFSET(type, member, offset) _Static_assert(offsetof(type, member) == offset, #type \".\" #member)")
    out.append("#define VALUE(name, value) _Static_assert((unsigned long long)(name) == value, #name)")
    out.append("")
    out.append("SIZE(%sStringView, 8, 4);" % P)
    out.append("OFFSET(%sStringView, data, 0);" % P)
    out.append("OFFSET(%sStringView, length, 4);" % P)
    out.append("SIZE(%sChainedStruct, 8, 4);" % P)
    out.append("OFFSET(%sChainedStruct, next, 0);" % P)
    out.append("OFFSET(%sChainedStruct, sType, 4);" % P)
    out.append("SIZE(%sEventString, 8, 4);" % P)
    out.append("SIZE(%sKey, 4, 4);" % P)
    out.append("SIZE(%sBool, 4, 4);" % P)
    for name, _ in spec.objects:
        out.append("SIZE(%s%s, 4, 4);" % (P, pascal(name)))
    out.append("")
    for s in spec.structs + [spec.header] + spec.records:
        out.append("SIZE(%s, %d, %d);" % (s.c_name, s.size, s.align))
        if s.kind == "extensible":
            out.append("OFFSET(%s, nextInChain, 0);" % s.c_name)
        elif s.kind == "record":
            out.append("OFFSET(%s, header, 0);" % s.c_name)
        for m in s.members:
            if m.ty.array:
                out.append("OFFSET(%s, %s, %d);" % (s.c_name, m.c_count_name, m.offset))
                out.append("OFFSET(%s, %s, %d);" % (s.c_name, m.c_name, m.offset + 4))
            else:
                out.append("OFFSET(%s, %s, %d);" % (s.c_name, m.c_name, m.offset))
        out.append("")
    for e in spec.enums:
        out.append("SIZE(%s, 4, 4);" % e.c_name)
        for name, value, _ in e.entries:
            out.append("VALUE(%s, 0x%XULL);" % (spec.enum_entry_c(e.name, name), value))
        out.append("")
    for b in spec.bitflags:
        out.append("SIZE(%s, %d, %d);" % (b.c_name, b.width // 8, b.width // 8))
        out.append("")
    out.append("VALUE(%sKey_Unidentified, 0x0ULL);" % P)
    for name, value in spec.named_keys:
        out.append("VALUE(%sKey_%s, 0x%XULL);" % (P, name, 0x01000000 | value))
    out.append("")
    out.append("VALUE(%s_ABI_VERSION, 0x%XULL);" % (P, spec.version))
    out.append("VALUE(%s_MAX_EVENT_SIZE, %dULL);" % (P, spec.max_event_size))
    out.append("VALUE(sizeof(%s), %dULL);" % (spec.header.c_name, HEADER_SIZE))
    out.append("")
    out.append("// `static const` flags are not constant expressions in C, so their values are")
    out.append("// checked when this runs instead (guest/tests/link_all.gen.c does not need them).")
    out.append("int %s_abi_check_flags(void) {" % FN_PREFIX)
    out.append("    int wrong = 0;")
    for b in spec.bitflags:
        for name, value, _ in b.entries:
            out.append("    wrong += %s != %s;" % (b.c_entry(name), flag_literal(b, value)))
    out.append("    return wrong;")
    out.append("}")
    return "\n".join(out) + "\n"


def emit_header_use(spec):
    """A translation unit that uses every INIT macro, compiled as several C and C++ standards."""
    P = PREFIX
    out = [BANNER]
    out.append("// Compile-only, as C99, C11, C++11 and C++17 with warnings as errors: the")
    out.append("// header, and every initializer macro in it, has to be valid in each.")
    out.append("")
    out.append("#include <wasmer/gui.h>")
    out.append("#include <wasmer/gui_names.h>")
    out.append("")
    out.append("size_t %s_header_use(void) {" % FN_PREFIX)
    out.append("    size_t total = 0;")
    out.append("    total += %sStatusName(%sStatus_Success) != NULL;" % (FN_PREFIX, PREFIX))
    out.append("    total += %sKeyName(%sKey_Enter) != NULL;" % (FN_PREFIX, PREFIX))
    out.append("    total += %sModifiersCount() + (size_t)%sModifiersValue(0) + (%sModifiersName(0) != NULL);" % (
        FN_PREFIX, FN_PREFIX, FN_PREFIX))
    out.append("    %sStringView view = %s_STRING_VIEW_INIT;" % (P, P))
    out.append("    total += view.length;")
    for s in spec.structs:
        if s.kind not in ("extensible", "standalone"):
            continue
        out.append("    {")
        out.append("        %s value = %s;" % (s.c_name, s.init_name))
        out.append("        total += sizeof value;")
        out.append("    }")
    out.append("    {")
    out.append("        uint64_t buffer[%s_MAX_EVENT_SIZE / 8];" % P)
    out.append("        const %s* event;" % spec.header.c_name)
    out.append("        buffer[0] = 0;")
    out.append("        for (event = %sEventFirst(buffer, 0); event != NULL; event = %sEventNext(buffer, 0, event)) {" % (
        FN_PREFIX, FN_PREFIX))
    out.append("            switch (event->type) {")
    out.append("                case %s: {" % spec.enum_entry_c("event_type", "key_down"))
    out.append("                    const %sKeyEvent* key = (const %sKeyEvent*)event;" % (P, P))
    out.append("                    total += %sEventGetString(event, key->text).length;" % FN_PREFIX)
    out.append("                    switch (key->key) {")
    out.append("                        case %sKey_Enter:" % P)
    out.append("                            total += 1;")
    out.append("                            break;")
    out.append("                        default:")
    out.append("                            break;")
    out.append("                    }")
    out.append("                    break;")
    out.append("                }")
    out.append("                default:")
    out.append("                    break;")
    out.append("            }")
    out.append("        }")
    out.append("    }")
    out.append("    return total;")
    out.append("}")
    return "\n".join(out) + "\n"


def zero_argument(ctype):
    if ctype.endswith("*"):
        return "NULL"
    if ctype in ("double", "float"):
        return "0.0"
    if ctype in ("size_t", "uint32_t", "int32_t", "uint64_t") or ctype.endswith("Bool"):
        return "0"
    return "(%s)0" % ctype


def emit_link_all(spec):
    """A program that imports the whole API and calls every function with nothing."""
    P = PREFIX
    out = [BANNER]
    out.append("// Calls every function of the API with null handles and null pointers and")
    out.append("// prints what each answered. Nothing here is a valid request, so no host may")
    out.append("// trap on it, and its import list is the complete API: instantiating it")
    out.append("// proves that a host provides every import with the signature the C compiler")
    out.append("// gives it.")
    out.append("")
    out.append("#include <stdio.h>")
    out.append("")
    out.append("#include <wasmer/gui.h>")
    out.append("")
    statuses = spec.enum_by_name["status"]
    out.append("static const char* status_name(%sStatus status) {" % P)
    out.append("    switch (status) {")
    for name, _, _ in statuses.entries:
        out.append("        case %s: return \"%s\";" % (statuses.c_entry(name), pascal(name)))
    out.append("        default: return \"?\";")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("int main(void) {")
    out.append("    uint32_t version = %sGetVersion();" % FN_PREFIX)
    out.append("    printf(\"host version %u.%u\\n\", version >> 16, version & 0xFFFFU);")
    count = 0
    for fn in spec.functions:
        count += 1
        if fn.c_name == FN_PREFIX + "GetVersion":
            continue
        args = ", ".join(zero_argument(t) for t, _ in spec.c_params(fn))
        call = "%s(%s)" % (fn.c_name, args)
        if fn.returns == "status":
            out.append("    printf(\"%s: %%s\\n\", status_name(%s));" % (fn.c_name, call))
        elif fn.returns == "bool":
            out.append("    printf(\"%s: %%s\\n\", %s ? \"true\" : \"false\");" % (fn.c_name, call))
        else:
            out.append("    %s;" % call)
            out.append("    printf(\"%s: returned\\n\");" % fn.c_name)
    out.append("    printf(\"%d functions\\n\");" % count)
    out.append("    return 0;")
    out.append("}")
    return "\n".join(out) + "\n"
