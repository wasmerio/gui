"""The JavaScript half's view of the ABI: numbers and record layouts.

A browser host has a part that runs on the page (js/gui_page.js). It writes
event records for the Rust host to queue and reads the commands the Rust host
sends, so it needs the same numbers the header has, and nothing else.
"""

import json

from spec import HEADER_SIZE, camel, pascal

BANNER = "// Generated by codegen/gen.py from spec/gui.json and spec/keys.json. Do not edit.\n"


def js_object(pairs, value=lambda v: "0x%X" % v):
    return "Object.freeze({\n" + "".join("  %s: %s,\n" % (k, value(v)) for k, v in pairs) + "})"


def field_kind(spec, ty):
    """How the page stores a record field."""
    if ty.kind == "prim":
        return {"uint32": "u32", "int32": "i32", "uint64": "u64", "float32": "f32", "float64": "f64",
                "key": "u32", "event_string": "str"}[ty.base]
    if ty.kind == "bitflag":
        return "u64" if spec.bitflag_by_name[ty.base].width == 64 else "u32"
    return "u32"  # enums and handles


def record_fields(spec, struct, base=0, prefix=""):
    out = []
    for m in struct.members:
        if m.ty.kind == "struct":
            nested = spec.struct_by_name[m.ty.base]
            out += record_fields(spec, nested, base + m.offset, camel(m.name) + "_")
        else:
            out.append((prefix + camel(m.name), base + m.offset, field_kind(spec, m.ty)))
    return out


def emit_abi(spec):
    out = [BANNER]
    out.append("export const IMPORT_MODULE = %s;" % json.dumps(spec.import_module))
    out.append("export const ABI_VERSION = 0x%X;" % spec.version)
    out.append("export const MAX_EVENT_SIZE = %d;" % spec.max_event_size)
    out.append("export const HEADER_SIZE = %d;" % HEADER_SIZE)
    out.append("")
    for e in spec.enums:
        if e.name == "physical_key":
            continue
        out.append("export const %s = %s;" % (
            e.rust_name, js_object([(spec.enum_entry_rust(e.name, n), v) for n, v, _ in e.entries])))
        out.append("")
    for b in spec.bitflags:
        wide = b.width == 64
        out.append("// %s bits%s" % (b.width, ": BigInt" if wide else ""))
        out.append("export const %s = %s;" % (
            pascal(b.name),
            js_object([(pascal(n), v) for n, v, _ in b.entries],
                      (lambda v: "0x%Xn" % v) if wide else (lambda v: "0x%X" % v))))
        out.append("")
    out.append("// KeyboardEvent.code -> WGUIPhysicalKey")
    out.append("export const PHYSICAL_KEYS = %s;" % js_object(spec.physical_keys))
    out.append("")
    out.append("// KeyboardEvent.key -> WGUIKey, for the named keys")
    out.append("export const NAMED_KEYS = %s;" % js_object([(n, 0x01000000 | v) for n, v in spec.named_keys]))
    out.append("")
    out.append("// The header of every record: field -> [offset, kind]")
    out.append("export const HEADER = Object.freeze({")
    for name, offset, kind in record_fields(spec, spec.header):
        out.append("  %s: [%d, '%s']," % (name, offset, kind))
    out.append("});")
    out.append("")
    out.append("// Records by name: the size of the fixed part, and field -> [offset, kind].")
    out.append("// 'str' fields hold {offset, length} of text appended after the fixed part.")
    out.append("export const RECORDS = Object.freeze({")
    for r in spec.records:
        out.append("  %s: Object.freeze({" % r.rust_name)
        out.append("    size: %d," % r.size)
        out.append("    fields: Object.freeze({")
        for name, offset, kind in record_fields(spec, r):
            if name.startswith("reserved"):
                continue
            out.append("      %s: [%d, '%s']," % (name, offset, kind))
        out.append("    }),")
        out.append("  }),")
    out.append("});")
    out.append("")
    out.append("// Event type -> the record it is, or null for the header alone.")
    out.append("export const EVENT_RECORDS = Object.freeze({")
    for e in spec.events:
        record = "'%s'" % spec.struct_by_name[e.record].rust_name if e.record else "null"
        out.append("  0x%X: %s, // %s" % (e.value, record, pascal(e.name)))
    out.append("});")
    return "\n".join(out) + "\n"
